  for (profile in names(python_golden)) {
    result <- calculate_tables(
      generate_synthetic_tables(bank_profile = profile),
      run_id = paste0("TEST-", profile)
    )
    expected <- python_golden[[profile]]
    expect_setequal(names(result$metrics), c(names(expected), "FLOOR_BINDING"))
    actual <- unlist(result$metrics[names(expected)], use.names = TRUE)
    allowed <- pmax(1e-5, abs(expected) * 1e-12)
    expect_true(all(abs(actual - expected) <= allowed),
                info = paste("Cross-language metric mismatch for", profile))
    expect_false(result$metrics$FLOOR_BINDING)
    expect_equal(length(result$results), 34L)
    expect_equal(length(result$parallel_results), 34L)
    expect_true(rwa_internal("calculation_successful")(result))
    expect_equal(rwa_internal("controls_passed")(result), 12L)
  }
})
